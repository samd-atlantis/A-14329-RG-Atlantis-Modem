"""Validate private overlays and collect evidence for a pinned development build."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

HERE = Path(__file__).resolve().parents[1]


def validate_unit(unit):
    if set(unit) != {"serial", "ssid", "wifi_password", "root_hash"}:
        raise ValueError("Unit record must contain exactly serial, ssid, wifi_password, root_hash")
    if not all(isinstance(v, str) for v in unit.values()):
        raise ValueError("Unit record values must be strings")
    if not re.fullmatch(r"[A-Za-z0-9-]{1,24}", unit["serial"]):
        raise ValueError("Invalid serial")
    if unit["ssid"] != "ATECH-" + unit["serial"]:
        raise ValueError("SSID must match the provisioned serial")
    if not re.fullmatch(r"[0-9a-f]{24}", unit["wifi_password"]):
        raise ValueError("Use the unique key generated by provision.py")
    if not re.fullmatch(r"\$6\$[./0-9A-Za-z]{1,16}\$[./0-9A-Za-z]{86}", unit["root_hash"]):
        raise ValueError("Invalid SHA512-crypt root hash")
    return unit["serial"]


def git(tree, *args):
    return subprocess.check_output(["git", "-C", str(tree), *args], text=True).strip()


def lock():
    return json.loads((HERE / "build-lock.json").read_text())


def verify_sources(tree):
    data = lock()
    if git(tree, "rev-parse", "refs/tags/" + data["release"]) != data["tag_object"]:
        raise ValueError("Unexpected OpenWrt release tag object")
    if git(tree, "rev-parse", "HEAD") != git(tree, "rev-parse", data["release"] + "^{commit}"):
        raise ValueError("OpenWrt checkout is not the pinned release commit")
    for name, feed in data["feeds"].items():
        if git(tree / "feeds" / name, "rev-parse", "HEAD") != feed["commit"]:
            raise ValueError("Unexpected feed revision: " + name)
        if git(tree / "feeds" / name, "diff", "HEAD", "--name-only"):
            raise ValueError("Feed contains unreviewed edits: " + name)


def collect_manifest(tree, output, mode, source_revision):
    verify_sources(tree)
    images = sorted(output.glob("*.bin"))
    if not images or not any("sysupgrade" in f.name for f in images):
        raise ValueError("Build did not produce a sysupgrade image")
    data = lock()
    artifacts = []
    for path in images:
        if "sysupgrade" in path.name and path.stat().st_size >= data["firmware_partition_bytes"]:
            raise ValueError("Sysupgrade image exceeds the target firmware partition")
        artifacts.append({"file": path.name, "bytes": path.stat().st_size,
                          "sha256": hashlib.sha256(path.read_bytes()).hexdigest()})
    manifest = {"schema": 1, "board": "A-14329-MB00", "profile": data["profile"],
                "source_revision": source_revision,
                "openwrt_commit": git(tree, "rev-parse", "HEAD"),
                "feeds": {n: f["commit"] for n, f in data["feeds"].items()},
                "mode": mode, "hardware_tested": False, "production_approved": False,
                "requires_confirmed_flash_bytes": data["flash_bytes"],
                "artifacts": artifacts}
    if mode == "private-unit-development":
        manifest["unit_serial"] = validate_unit(json.loads((tree / "files/etc/gateway/unit.json").read_text()))
    (output / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (output / "SHA256SUMS").write_text("".join(f'{a["sha256"]}  {a["file"]}\n' for a in artifacts))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    v = sub.add_parser("validate-unit")
    v.add_argument("file", type=Path)
    f = sub.add_parser("feeds")
    f.add_argument("file", type=Path)
    s = sub.add_parser("verify-sources")
    s.add_argument("tree", type=Path)
    m = sub.add_parser("manifest")
    m.add_argument("tree", type=Path)
    m.add_argument("output", type=Path)
    m.add_argument("mode", choices=["unprovisioned-validation", "private-unit-development"])
    m.add_argument("source_revision")
    args = parser.parse_args()
    if args.command == "validate-unit":
        print(validate_unit(json.loads(args.file.read_text())))
    elif args.command == "feeds":
        args.file.write_text("".join(f'src-git {n} {f["url"]}^{f["commit"]}\n'
                                     for n, f in lock()["feeds"].items()))
    elif args.command == "verify-sources":
        verify_sources(args.tree)
    else:
        collect_manifest(args.tree, args.output, args.mode, args.source_revision)


if __name__ == "__main__":
    main()
